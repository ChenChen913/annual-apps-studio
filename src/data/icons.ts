export const ICON_CATEGORIES: IconCategory[] = ['AI', '浏览器', '开发', '办公', '设计', '媒体', '效率', '系统']

export const ICON_MAP = new Map(ICON_LIBRARY.map((icon) => [icon.id, icon]))

export function getIconSrc(app: { libraryId: string | null; iconSrc: string | null }) {
  if (app.iconSrc) return app.iconSrc
  if (app.libraryId?.startsWith('creator:')) {
    return CREATOR_ICON_MAP[app.libraryId.slice('creator:'.length)] ?? null
  }
  if (app.libraryId) return ICON_MAP.get(app.libraryId)?.src ?? null
  return null
}

export function getIconLabel(id: string | null | undefined) {
  if (!id) return ''
  return ICON_MAP.get(id)?.label ?? ''
}

export function searchIcons(query: string, category?: IconCategory | '全部') {
  const value = query.trim().toLowerCase()
  const list = category && category !== '全部'
    ? ICON_LIBRARY.filter((icon) => icon.category === category)
    : ICON_LIBRARY
  if (!value) return list
  return list.filter((icon) => {
    const haystack = `${icon.label} ${icon.keywords}`.toLowerCase()
    return value.split(/\s+/).every((part) => haystack.includes(part))
  })
}
